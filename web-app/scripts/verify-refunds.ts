/**
 * 退款配对引擎的回归校验。
 *
 * 样本是合成的——真实流水含个人消费记录，不进仓库。这里的每个用例都对应
 * docs/adr/0004-退款配对剔除.md 里记录的一个真实陷阱，改动配对逻辑时先跑这个。
 *
 *   npm run verify:refunds
 */
import { matchRefunds, isRefundRow, occupiedRows } from '../src/refundMatcher';
import { CCBRow } from '../src/types';

let failures = 0;

function row(
  摘要: string,
  交易日期: string,
  交易金额: number,
  交易地点附言: string,
  对方账号与户名 = ''
): CCBRow {
  return {
    序号: '',
    摘要,
    币别: '人民币元',
    钞汇: '钞',
    交易日期,
    交易金额: String(交易金额),
    账户余额: '',
    交易地点附言,
    对方账号与户名,
  };
}

function check(name: string, actual: number, expected: number, extra = '') {
  const ok = actual === expected;
  if (!ok) failures++;
  console.log(`${ok ? ' ok ' : 'FAIL'}  ${name}  (期望 ${expected}，实际 ${actual})${extra}`);
}

// ---- 用例 1：全额 1:1。出账侧户名被打码，只能靠附言末段认商户 ----
{
  const rows = [
    row('消费', '20260910', -150, '财付通-微信支付-美团平台商户', 'Z******0010/***商户'),
    row('消费退货', '20260912', 150, '财付通-美团平台商户', '20880115192499520156/美团平台商户'),
  ];
  const m = matchRefunds(rows);
  check('全额 1:1 应配对', m.length, 1);
  check('  配对笔数应为 1 笔退款', m[0]?.退款行.length ?? 0, 1);
}

// ---- 用例 2：拆分退款，一笔出账被 2 笔退款合计冲平 ----
{
  const rows = [
    row('消费', '20260917', -628, '支付宝-中国铁路网络有限公司', 'Z******0010/***公司'),
    row('消费退货', '20260917', 314, '支付宝-中国铁路网络有限公司', '1/中国铁路网络有限公司'),
    row('消费退货', '20260917', 314, '支付宝-中国铁路网络有限公司', '1/中国铁路网络有限公司'),
  ];
  const m = matchRefunds(rows);
  check('拆分退款 628=314×2 应配对', m.length, 1);
  check('  层级应为 split', m[0]?.kind === 'split' ? 1 : 0, 1);
}

// ---- 用例 3：金额相同但商户不同，不能配（真实流水里出现过 5 元的巧合） ----
{
  const rows = [
    row('消费', '20260925', -5, '财付通-微信支付-成都豪腾商贸有限公司', 'Z******0010/***公司'),
    row('消费退货', '20260928', 5, '财付通-广记昌鸡煲饭店（西丽悦方店）', '9/广记昌鸡煲饭店（西丽悦方店）'),
  ];
  check('同额不同商户不得配对', matchRefunds(rows).length, 0);
}

// ---- 用例 4：支出日期晚于退款日期，不能配 ----
{
  const rows = [
    row('消费', '20261005', -18, '支付宝-中国铁路网络有限公司', 'Z******0010/***公司'),
    row('消费退货', '20260918', 18, '支付宝-中国铁路网络有限公司', '1/中国铁路网络有限公司'),
  ];
  check('原支出晚于退款的不得配对', matchRefunds(rows).length, 0);
}

// ---- 用例 5：部分退款（退款小于支出）本轮不处理，应原样保留 ----
{
  const rows = [
    row('消费', '20260906', -313.06, '支付宝-天猫-佛山市瑞翌电子商务有限公司', 'Z******0010/***公司'),
    row('消费退货', '20260908', 271, '支付宝-佛山市瑞翌电子商务有限公司', '7/佛山市瑞翌电子商务有限公司'),
  ];
  check('部分退款不得配对', matchRefunds(rows).length, 0);
}

// ---- 用例 6：完全没有原单的退款，应保留 ----
{
  const rows = [
    row('消费', '20260903', -84, '支付宝-义乌市力福纺织品有限公司', 'Z******0010/***公司'),
    row('消费退货', '20260901', 13.9, '财付通-视频号小店', '1669561353/视频号小店'),
  ];
  check('无原单的退款不得配对', matchRefunds(rows).length, 0);
}

// ---- 用例 7：退款语义只认摘要；普通消费不应被当成退款 ----
{
  const rows = [
    row('消费', '20260910', -50, '财付通-微信支付-某商户', 'Z/***商户'),
    row('消费', '20260911', 50, '财付通-某商户', '1/某商户'),
  ];
  check('正向的普通入账不是退款', rows.filter(isRefundRow).length, 0);
  check('  因而也不会产生配对', matchRefunds(rows).length, 0);
}

// ---- 用例 8：配对占据的行应覆盖出账与全部退款 ----
{
  const rows = [
    row('消费', '20260917', -628, '支付宝-中国铁路网络有限公司', 'Z******0010/***公司'),
    row('消费退货', '20260917', 314, '支付宝-中国铁路网络有限公司', '1/中国铁路网络有限公司'),
    row('消费退货', '20260917', 314, '支付宝-中国铁路网络有限公司', '1/中国铁路网络有限公司'),
  ];
  check('占用行数应为 3', occupiedRows(matchRefunds(rows)).size, 3);
}

console.log('');
if (failures > 0) {
  console.log(`${failures} 项未通过`);
  process.exit(1);
}
console.log('全部通过');
